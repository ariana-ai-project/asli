/* ============================================================
   یکسان‌سازیِ دوم (frontend/tamin-poshtibani/catalog-canon.mjs) — تصمیم‌های مدیر، مهر ۱۴۰۵

   نمونه‌ها از خودِ فهرست اقلامِ دیتابیس تولید برداشته شده‌اند (ممیزی دوم):
     - نام هم‌معنا: «آرماتور» همان «میلگرد» است؛ غلط‌های املایی به نام درست
     - «نمره» لایهٔ مستقل نیست: قطر، سطح مقطع، ارتفاع یا یال — بسته به نوع قلم
     - ورق ← ضخامت + مساحت (متر مربع)؛ قوطی/پروفیل ← ضخامت + محیط؛ نبشی ← یال‌ها
     - واحد مرجعِ هر لایه
   ============================================================ */
import test from "node:test";
import assert from "node:assert/strict";
import * as R from "../../../frontend/tamin-poshtibani/catalog-rules.mjs";
import * as C from "../../../frontend/tamin-poshtibani/catalog-canon.mjs";
import { HEAD_RULES } from "../../../frontend/tamin-poshtibani/catalog-head-rules.mjs";

const q = (v, u, i) => ({ v: String(v), n: [v], u, ...(i ? { i: 1 } : {}) });
const L = (head, layers) => C.canonLayers(head, layers);

test("نام هم‌معنا: آرماتور ← میلگرد با همان جنس؛ غلط‌های املایی به نام درست", () => {
  assert.equal(C.canonHead("آرماتور آهنی"), "میلگرد آهنی");
  assert.equal(C.canonHead("آرماتور کامپوزیت"), "میلگرد کامپوزیت");
  assert.equal(C.canonHead("آرماتور"), "میلگرد");
  assert.equal(C.canonHead("پیج"), "پیچ");
  assert.equal(C.canonHead("یپچ"), "پیچ");
  assert.equal(C.canonHead("ناودونی"), "ناودانی");
  assert.equal(C.canonHead("میلگرد آهنی"), "میلگرد آهنی", "نام استاندارد دست نمی‌خورد");
  assert.equal(C.canonHead("ورق آهنی"), "ورق آهنی");
  /* هم‌معنای بی‌جنس که نامِ استانداردش جنس دارد: جنس از خودِ قلم */
  assert.equal(C.canonHead("شلنگ", { title: "شلنگ آب 1 اینچ", layers: {} }), "شیلنگ لاستیکی", "شیلنگِ بی‌جنس = لاستیکی (عرفِ شیلنگ)");
  assert.deepEqual(C.aliasBases("میلگرد"), ["آرماتور"]);
  /* هر هم‌معنا به نامی می‌رود که خودش هم‌معنای دیگری نیست (زنجیره نمی‌سازد) */
  for (const [a, b] of Object.entries(C.HEAD_ALIASES)) {
    assert.equal(C.canonBase(b), b, `${a} ← ${b}: مقصد خودش نام استاندارد است`);
    assert.notEqual(R.keyOf(a), R.keyOf(b));
  }
});

test("نمره ← لایهٔ واقعی: قطر (پیچ، میلگرد)، سطح مقطع (سیم)، ارتفاع (ناودانی، تیرآهن)، یال (نبشی)", () => {
  assert.deepEqual(L("پیچ", { "نمره": "16", "طول": q(60, "میلی‌متر") }), { "طول": q(60, "میلی‌متر"), "قطر": q(16, "میلی‌متر", 1) }, "پیچ نمره ۱۶ = M16");
  assert.deepEqual(L("میلگرد آهنی", { "نمره": "12", "رده": "A3" }), { "رده": "A3", "قطر": q(12, "میلی‌متر", 1) });
  assert.deepEqual(L("آرماتور آهنی", { "نمره": "28" }), { "قطر": q(28, "میلی‌متر", 1) }, "هم‌معنا هم همان قاعده");
  assert.deepEqual(L("سیم", { "نمره": "2.5", "نوع": "افشان" }), { "نوع": "افشان", "سطح مقطع": q(2.5, "میلی‌متر مربع", 1) });
  assert.deepEqual(L("سیم مسی", { "نمره": "50 میلی‌متر" }), { "سطح مقطع": q(50, "میلی‌متر مربع", 1) }, "«۵۰ mm»ِ سیم ارت کوتاه‌نوشتِ میلی‌متر مربع است");
  assert.deepEqual(L("سیم", { "نمره": "0.7 میلی‌متر", "نوع": "لاکی" }), { "نوع": "لاکی", "قطر": q(0.7, "میلی‌متر") }, "اندازهٔ طولیِ صریح قطرِ مفتول است");
  assert.deepEqual(L("ناودانی آهنی", { "نمره": "16" }), { "ارتفاع": q(16, "سانتی‌متر", 1) }, "ناودانی ۱۶ = جانِ ۱۶۰ میلی‌متری");
  assert.deepEqual(L("تیر آهن", { "نمره": "20" }), { "ارتفاع": q(20, "سانتی‌متر", 1) });
  assert.deepEqual(L("نبشی آهنی", { "نمره": "5" }), { "یال برابر": q(5, "سانتی‌متر", 1) }, "نبشی ۵ = یال ۵۰ میلی‌متر");
  assert.deepEqual(L("نبشی آهنی", { "نمره": "30", "ضخامت": q(2.5, "میلی‌متر") }), { "ضخامت": q(2.5, "میلی‌متر"), "یال برابر": q(30, "میلی‌متر", 1) }, "نمرهٔ بزرگ‌تر از ۲۰ میلی‌متر است");
  assert.deepEqual(L("لوله", { "نمره": "1/2" }), { "قطر": { v: "1/2", n: [0.5], u: "اینچ", i: 1 } }, "کسرِ اینچیِ سره در لوله");
  assert.deepEqual(L("لوله", { "نمره": "8 اینچ" }), { "قطر": q(8, "اینچ") }, "واحدِ صریح مقدم است");
  assert.deepEqual(L("روغن", { "نمره": "30" }), { "گرانروی": "30" }, "نمرهٔ روغن گرانروی است (نام، نه عدد)");
  assert.deepEqual(L("پیچ", { "نمره": "8.8", "اندازه": "M10" }), { "اندازه": "M10", "رده": "8.8" }, "کلاسِ استحکام، نه قطر");
  /* لایهٔ مقصد اگر مقدار دارد، نمره چیزِ دیگری است و می‌ماند (مهرهٔ دنباله‌دار: رزوه + شیلنگ) */
  const nut = L("مهره", { "قطر": { v: "1/2", n: [0.5], u: "اینچ" }, "نمره": "12" });
  assert.equal(nut["نمره"], "12"); assert.equal(nut["قطر"].u, "اینچ");
  /* نوع قلمی که معنای نمره‌اش تصمیم نشده: دست نمی‌خورد */
  assert.deepEqual(L("آچار", { "نمره": "24", "نوع": "شلاقی" }), { "نمره": "24", "نوع": "شلاقی" });
});

test("ورق ← ضخامت + مساحت (متر مربع): کوچک‌ترین بُعد ضخامت است، واحدِ ضلع از بزرگی", () => {
  assert.deepEqual(L("ورق آهنی", { "ضخامت": q(60, "میلی‌متر"), "طول": q(11500, "میلی‌متر"), "عرض": q(2400, "میلی‌متر") }),
    { "ضخامت": q(60, "میلی‌متر"), "مساحت": q(27.6, "متر مربع") }, "ورق ۶۰×۲۴۰۰×۱۱۵۰۰");
  assert.deepEqual(L("ورق آهنی", { "ابعاد": { v: "20×1000×2000", n: [20, 1000, 2000], u: "" } }),
    { "ضخامت": q(20, "میلی‌متر", 1), "مساحت": q(2, "متر مربع", 1) }, "سه‌بعدیِ بی‌واحد");
  assert.deepEqual(L("ورق آهنی", { "ضخامت": q(2, "میلی‌متر"), "ابعاد": { v: "2×1", n: [2, 1], u: "" } }),
    { "ضخامت": q(2, "میلی‌متر"), "مساحت": q(2, "متر مربع", 1) }, "«ورق ۲ میل ۲×۱»: ضلع‌های کوچک متر");
  assert.deepEqual(L("ورق آهنی", { "ضخامت": q(5, "میلی‌متر"), "ابعاد": { v: "1520×650", n: [1520, 650], u: "میلی‌متر", i: 1 } }),
    { "ضخامت": q(5, "میلی‌متر"), "مساحت": q(0.988, "متر مربع", 1) });
  assert.deepEqual(L("ورق گالوانیزه", { "ابعاد": { v: "1.25×2", n: [1.25, 2], u: "متر" } }), { "مساحت": q(2.5, "متر مربع") }, "واحدِ صریح");
  /* فقط عرض: مساحت معلوم نیست — دست نمی‌خورد */
  const w = { "ضخامت": q(30, "میلی‌متر"), "عرض": q(1.25, "متر") };
  assert.deepEqual(L("ورق آهنی", w), w);
  assert.deepEqual(L("ورق استیل", { "ضخامت": { v: "0.1", n: [0.1], u: "" } }), { "ضخامت": q(0.1, "میلی‌متر", 1) }, "ضخامتِ بی‌واحد میلی‌متر است");
  assert.deepEqual(L("ورق گیر", { "ابعاد": { v: "2×1", n: [2, 1], u: "" } }), { "ابعاد": { v: "2×1", n: [2, 1], u: "" } }, "«ورق گیر» ابزار است، ورق نیست");
});

test("مقطع توخالی (قوطی، پروفیل) ← ضخامت + محیط", () => {
  assert.deepEqual(L("قوطی آهنی", { "ابعاد": { v: "3×5", n: [3, 5], u: "" }, "طول": q(3, "متر") }),
    { "طول": q(3, "متر"), "محیط": q(160, "میلی‌متر", 1) }, "قوطی ۳×۵ = ۳۰×۵۰ میلی‌متر");
  assert.deepEqual(L("قوطی آهنی", { "ابعاد": { v: "40×40", n: [40, 40], u: "" } }), { "محیط": q(160, "میلی‌متر", 1) },
    "۳۰×۵۰ و ۴۰×۴۰ هر دو محیطِ ۱۶۰ دارند — تصمیم مدیر: مقطع توخالی با محیط سنجیده می‌شود");
  assert.deepEqual(L("پروفیل", { "ابعاد": { v: "40×20×2", n: [40, 20, 2], u: "" } }), { "محیط": q(120, "میلی‌متر", 1), "ضخامت": q(2, "میلی‌متر", 1) });
  assert.deepEqual(L("پروفیل", { "ابعاد": { v: "40×40×600", n: [40, 40, 600], u: "" } }), { "محیط": q(160, "میلی‌متر", 1), "طول": q(600, "میلی‌متر", 1) }, "عددِ خیلی بزرگ طولِ شاخه است");
});

test("نبشی ← ضخامت + یال برابر، یا یال بزرگ و یال کوچک", () => {
  assert.deepEqual(L("نبشی آهنی", { "ابعاد": { v: "50×50×5", n: [50, 50, 5], u: "میلی‌متر", i: 1 } }), { "یال برابر": q(50, "میلی‌متر", 1), "ضخامت": q(5, "میلی‌متر", 1) });
  assert.deepEqual(L("نبشی گالوانیزه", { "ابعاد": { v: "70×50×2", n: [70, 50, 2], u: "میلی‌متر" } }),
    { "یال بزرگ": q(70, "میلی‌متر"), "یال کوچک": q(50, "میلی‌متر"), "ضخامت": q(2, "میلی‌متر") }, "یال‌های نابرابر، واحدِ صریح");
  assert.deepEqual(L("نبشی آهنی", { "ابعاد": { v: "75×75", n: [75, 75], u: "" } }), { "یال برابر": q(75, "میلی‌متر", 1) });
  const odd = { "ابعاد": { v: "8×10×10", n: [8, 10, 10], u: "" } };
  assert.deepEqual(L("نبشی آهنی", odd), odd, "ضخامتِ ≥ نصفِ یال خوانا نیست — دست نمی‌خورد");
  assert.deepEqual(L("نبشی گالوانیزه", { "ضخامت": q(40, "میلی‌متر") }), { "یال برابر": q(40, "میلی‌متر") }, "«نبشی ۴۰ میل» ضخامتِ ۴۰ نیست، یال است");
});

test("هم‌توانی: دوباره زدنِ یکسان‌سازی چیزی را عوض نمی‌کند", () => {
  const cases = [
    ["ورق آهنی", { "ابعاد": { v: "20×1000×2000", n: [20, 1000, 2000], u: "" } }],
    ["نبشی آهنی", { "نمره": "6 / 63", "طول": q(6, "متر") }],
    ["قوطی آهنی", { "ابعاد": { v: "18×14", n: [18, 14], u: "" }, "ضخامت": q(8, "میلی‌متر") }],
    ["پیچ", { "نمره": "16" }], ["سیم", { "نمره": "4" }], ["ناودانی آهنی", { "نمره": "6.5" }],
  ];
  for (const [h, l] of cases) { const a = L(h, l); assert.deepEqual(L(h, a), a, h); }
  const s = C.canonStructure({ head: "آرماتور آهنی", layers: { "نمره": "12" } });
  assert.deepEqual(C.canonStructure(s), s);
  assert.equal(s.head, "میلگرد آهنی");
});

test("واحد مرجعِ هر لایه و تبدیل به آن", () => {
  assert.deepEqual(R.toRef("طول", q(6, "متر")), { n: [6000], u: "میلی‌متر", same: false });
  assert.deepEqual(R.toRef("ضخامت", q(0.2, "سانتی‌متر")), { n: [2], u: "میلی‌متر", same: false });
  assert.deepEqual(R.toRef("مساحت", q(2, "متر مربع")), { n: [2], u: "متر مربع", same: true });
  assert.deepEqual(R.toRef("توان", q(750, "وات")), { n: [0.75], u: "کیلووات", same: false });
  assert.equal(R.refUnitOf("توان", q(10, "کیلوولت‌آمپر")), "کیلوولت‌آمپر", "توانِ ظاهری به کیلووات نمی‌رود");
  assert.equal(R.refUnitOf("ظرفیت", q(10, "تن")), "تن");
  assert.equal(R.refUnitOf("ظرفیت", q(200, "لیتر")), "لیتر");
  /* توانِ گرمایی همان توان است: ۱۰ هزار کیلوکالری بر ساعت ≈ ۱۱٫۶ کیلووات */
  assert.equal(R.layerKey("توان", q(10000, "کیلوکالری بر ساعت")), R.layerKey("توان", q(11630, "وات")));
  /* هر لایهٔ کمّی واحد مرجع دارد و بُعدِ مرجع با بُعدِ مجازِ لایه می‌خواند */
  for (const [k, dims] of Object.entries(R.QUANT)) {
    if (dims.includes("*")) continue;
    const ref = R.LAYER_REF[k];
    assert.ok(ref && R.UNITS[ref], `${k}: واحد مرجع`);
    assert.ok(dims.includes(R.UNITS[ref].dim), `${k}: بُعدِ ${ref}`);
    assert.ok(!R.LAYER_DEFAULT_UNIT[k] || dims.includes(R.UNITS[R.LAYER_DEFAULT_UNIT[k]].dim), `${k}: پیش‌فرض`);
  }
});

test("فهرست لایه‌ها: بی «نمره»، با مساحت و محیط و یال‌ها — نام لایهٔ تازه با فرم کارشناس هم خوانده می‌شود", () => {
  const names = R.layerList([{ fa: "قطر", en: "diameter" }, { fa: "نمره", en: "gauge" }, { fa: "جنس", en: "material" }]).map((l) => l.fa);
  assert.deepEqual(names, ["قطر", "جنس", "مساحت", "محیط", "یال برابر", "یال بزرگ", "یال کوچک"]);
  for (const k of ["مساحت", "محیط", "یال برابر", "یال بزرگ", "یال کوچک"]) assert.ok(R.QUANT[k], `${k} کمّی است و فیلد واحد دارد`);
  assert.deepEqual(R.quantWith("مساحت", "2.5", "مترمربع"), q(2.5, "متر مربع"));
  assert.equal(R.quantWith("یال برابر", "5", "کیلوگرم"), null, "بُعدِ واحد با لایه نمی‌خواند");
});

test("جدول نمره و مقطع‌ها سالم است: هر لایهٔ مقصد استاندارد و هر واحد شناخته", () => {
  const std = new Set([...R.layerList([{ fa: "رده" }, { fa: "گرانروی" }]).map((l) => l.fa), ...Object.keys(R.QUANT)]);
  for (const [head, [layer, unit]] of Object.entries(C.NOMRE)) {
    assert.ok(std.has(layer), `${head}: لایهٔ «${layer}»`);
    if (unit) assert.ok(R.UNITS[unit] && R.QUANT[layer] && R.QUANT[layer].includes(R.UNITS[unit].dim), `${head}: واحدِ «${unit}» در «${layer}»`);
    /* کلید یا نامِ پایه است، یا «پایه + جنس»ِ نوع قلمی که جنس جزء نامش است («سیم آهنی») */
    const sh = R.splitHead(head, HEAD_RULES);
    assert.ok(sh.base === head || (sh.mat && sh.rule && sh.rule.r === "f"), `${head}: نامِ پایه یا «پایه + جنس»`);
  }
  assert.deepEqual(L("سیم آهنی", { "نمره": "6" }), { "قطر": q(6, "میلی‌متر", 1) }, "مفتولِ آهنی: قطر، نه سطح مقطع");
  assert.deepEqual(L("سیم مسی", { "نمره": "16" }), { "سطح مقطع": q(16, "میلی‌متر مربع", 1) });
  for (const h of Object.keys(C.SHAPES)) assert.equal(R.splitHead(h, HEAD_RULES).base, h);
});
