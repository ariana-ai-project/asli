/* ============================================================
   تبدیلِ ایستا/پویای واحدِ خرید به واحد مرجع — frontend/tamin-poshtibani/catalog-units.mjs
   (تصمیم مدیر، مهر ۱۴۰۵)

   چرا این تست وجود دارد: فایل ۴ برای هر (نوع قلم، واحد) یک نرخ ثابت داشت، و «۱ ورق = ۱۱۰ کیلوگرم» برای
   ورقِ ۸ میلِ ۲ متری (۱۲۶ کیلوگرم) و ۹ متری (۵۶۵ کیلوگرم) یکی بود. تبدیلِ «پویا» حالا برای هر قلم با فرمول
   از لایه‌هایش حساب می‌شود. عددهای طلایی همان «محاسبهٔ مهندسیِ» خودِ فایل ۴ برای همین اقلام است
   (item_rates) — فرمول‌ها باید همان‌ها را بسازند، جز جایی که فایل غلط بود (پایین‌تر گفته شده).
   ============================================================ */
import test from "node:test";
import assert from "node:assert/strict";
import { convert, familyOf, purchaseUnit, PURCHASE_UNITS } from "../../../frontend/tamin-poshtibani/catalog-units.mjs";
import { canonLayers } from "../../../frontend/tamin-poshtibani/catalog-canon.mjs";

const q = (v, u, i) => ({ v: String(v), n: [v], u, ...(i ? { i: 1 } : {}) });
const conv = (head, layers, from, to) => convert({ head, layers: canonLayers(head, layers) }, from, to);
const near = (a, b, tol = 0.005) => assert.ok(a != null && Math.abs(a - b) <= tol * Math.abs(b), `${a} ≉ ${b}`);

test("واحدهای خرید: هر ۲۳ واحدِ سوابق شناخته است؛ «کیلوگرم» و «کیلو گرم» یکی", () => {
  for (const u of ["عدد", "کیلو گرم", "دست", "متر", "بسته", "لیتر", "دستگاه", "جفت", "تن", "قوطی", "حلقه", "شاخه", "متر مربع", "پاکت", "ورق",
    "شیشه", "رول", "جعبه", "متر مکعب", "رشته", "قرقره", "تخته", "جلد"]) assert.ok(PURCHASE_UNITS[purchaseUnit(u)], u);
  assert.equal(purchaseUnit("کیلوگرم"), "کیلو گرم");
  assert.equal(purchaseUnit("مترمربع"), "متر مربع");
  assert.equal(purchaseUnit("فرسخ"), null);
});

test("ایستا: ضریب از خودِ دو واحد، برای همهٔ اقلام یکی", () => {
  const s = (from, to, want) => { const r = convert({ head: "هر چیز", layers: {} }, from, to); assert.deepEqual([r.type, r.rate], ["static", want], `${from} → ${to}`); };
  s("تن", "کیلو گرم", 1000); s("کیلو گرم", "تن", 0.001); s("متر مکعب", "لیتر", 1000);
  s("دستگاه", "عدد", 1); s("عدد", "حلقه", 1); s("پاکت", "عدد", 1); s("شاخه", "عدد", 1);
  s("جفت", "عدد", 2); s("عدد", "جفت", 0.5);
  assert.equal(convert({ head: "x", layers: {} }, "فرسخ", "متر").type, "unknown");
});

test("پویا — ورق: مساحت × ضخامت × چگالی (همان محاسبهٔ مهندسیِ فایل ۴)", () => {
  near(conv("ورق آهنی", { "ضخامت": q(30, "میلی‌متر"), "ابعاد": { v: "1000×600", n: [1000, 600], u: "میلی‌متر" } }, "عدد", "کیلو گرم").rate, 141.3);
  near(conv("ورق گالوانیزه", { "ضخامت": q(6, "میلی‌متر"), "مساحت": q(2, "متر مربع", 1) }, "ورق", "کیلو گرم").rate, 94.2);
  near(conv("ورق آهنی", { "ضخامت": q(10, "میلی‌متر") }, "متر مربع", "کیلو گرم").rate, 78.5);
  near(conv("ورق استیل", { "ضخامت": q(1, "میلی‌متر"), "مساحت": q(2, "متر مربع") }, "ورق", "کیلو گرم").rate, 15.86, 0.01);
  /* ورقِ بی مساحت: فرمولی کار نمی‌کند و می‌گوید چه کم است */
  const r = conv("ورق آهنی", { "ضخامت": q(8, "میلی‌متر") }, "ورق", "کیلو گرم");
  assert.deepEqual([r.type, r.rate, r.used], ["dynamic", null, -1]);
  assert.ok(r.missing.includes("مساحت"));
  assert.match(r.formulas[1].label, /مساحت \(متر مربع\) × ضخامت \(میلی‌متر\) × چگالیِ آهنی 7\.85/);
  /* جنسِ گفته‌نشده در نامِ نوع قلم: عرفِ ورق (آهنی) با علامتِ «ضمنی» */
  assert.match(conv("ورق", { "ضخامت": q(8, "میلی‌متر") }, "ورق", "کیلو گرم").formulas[1].label, /چگالیِ آهنی \(ضمنی\) 7\.85/);
  /* پلیت (طول و عرضِ جدا): کیلوگرم ← عدد */
  near(conv("پلیت", { "ضخامت": q(10, "میلی‌متر"), "طول": q(250, "میلی‌متر"), "عرض": q(250, "میلی‌متر") }, "کیلو گرم", "عدد").rate, 0.2038, 0.01);
});

test("پویا — مقاطع طولی: وزن هر متر از قطر، یال، محیط یا جدولِ ارتفاع", () => {
  near(conv("میلگرد آهنی", { "قطر": q(10, "میلی‌متر", 1) }, "متر", "کیلو گرم").rate, 0.617, 0.01);
  near(conv("میلگرد آهنی", { "قطر": q(28, "میلی‌متر", 1) }, "متر", "کیلو گرم").rate, 4.83, 0.01);
  near(conv("نبشی آهنی", { "یال برابر": q(40, "میلی‌متر", 1), "ضخامت": q(4, "میلی‌متر", 1) }, "کیلو گرم", "متر").rate, 0.419);
  near(conv("نبشی آهنی", { "یال برابر": q(75, "میلی‌متر", 1), "ضخامت": q(5, "میلی‌متر", 1) }, "کیلو گرم", "متر").rate, 0.1757);
  near(conv("لوله آهنی", { "قطر": q(40, "میلی‌متر"), "ضخامت": q(3, "میلی‌متر") }, "کیلو گرم", "متر").rate, 0.3653);
  near(conv("لوله آهنی", { "قطر": q(60, "میلی‌متر", 1), "ضخامت": q(4, "میلی‌متر") }, "کیلو گرم", "متر").rate, 0.181, 0.01);
  /* لوله با قطر اسمیِ اینچی و بی ضخامت: جدولِ لولهٔ استاندارد */
  near(conv("لوله گالوانیزه", { "قطر": q(2, "اینچ") }, "کیلو گرم", "متر").rate, 1 / 5.1);
  near(conv("قوطی آهنی", { "محیط": q(200, "میلی‌متر", 1), "ضخامت": q(2, "میلی‌متر") }, "کیلو گرم", "متر").rate, 1 / 3.14);
  near(conv("تسمه آهنی", { "عرض": q(50, "میلی‌متر"), "ضخامت": q(5, "میلی‌متر") }, "متر", "کیلو گرم").rate, 1.9625);
  /* تیرآهن IPE و ناودانی UNP از روی ارتفاع (نمره به سانتی‌متر) */
  near(conv("تیر آهن", { "ارتفاع": q(16, "سانتی‌متر", 1) }, "کیلو گرم", "شاخه").rate, 0.005274);
  near(conv("تیر آهن", { "ارتفاع": q(24, "سانتی‌متر", 1) }, "تن", "شاخه").rate, 2.714);
  near(conv("ناودانی آهنی", { "ارتفاع": q(16, "سانتی‌متر", 1) }, "شاخه", "کیلو گرم").rate, 112.8);
  near(conv("ناودانی آهنی", { "ارتفاع": q(6, "سانتی‌متر", 1) }, "متر", "کیلو گرم").rate, 7.09, 0.01);
  /* سیم مسی: سطح مقطع × چگالی × روکش (فایل ۴: ۰٫۰۱۱۲ × سطح مقطع) */
  near(conv("سیم", { "سطح مقطع": q(1.5, "میلی‌متر مربع", 1) }, "متر", "کیلو گرم").rate, 0.0168);
  near(conv("سیم مسی", { "سطح مقطع": { v: "16×1", n: [16, 1], u: "میلی‌متر مربع", i: 1 } }, "متر", "کیلو گرم").rate, 0.1792);
  /* استرندِ ۰٫۶ اینچی ۱٫۱۰ کیلوگرم در متر است (ASTM A416)؛ فایل ۴ با فرمولِ میلگردِ توپر ۱٫۴۳ گرفته بود */
  near(conv("سیم بکسل آهنی", { "قطر": q(0.6, "اینچ"), "نوع": "استرند" }, "کیلو گرم", "متر").rate, 1 / 1.103, 0.01);
  near(conv("سیم بکسل آهنی", { "قطر": q(20, "میلی‌متر", 1) }, "کیلو گرم", "متر").rate, 1 / 1.6);
});

test("پویا — شاخه: طولِ لایه، وگرنه شاخهٔ استاندارد (فرضِ آشکار)", () => {
  /* فایل ۴ شاخهٔ میلگرد را ۶ متر گرفته بود؛ شاخهٔ میلگرد در بازار ۱۲ متر است */
  near(conv("میلگرد آهنی", { "قطر": q(16, "میلی‌متر", 1) }, "شاخه", "کیلو گرم").rate, 12 * 1.578, 0.01);
  near(conv("میلگرد آهنی", { "قطر": q(16, "میلی‌متر", 1), "طول": q(6, "متر") }, "شاخه", "کیلو گرم").rate, 6 * 1.578, 0.01);
  /* «میلگرد بستر خرپایی ۱۵ سانتی»: ۱۵ سانتی پهنای خرپاست نه طولِ شاخه */
  const r = conv("میلگرد آهنی", { "قطر": q(10, "میلی‌متر", 1), "طول": q(15, "سانتی‌متر") }, "شاخه", "کیلو گرم");
  near(r.rate, 12 * 0.6165, 0.01);
  assert.equal(conv("لوله PVC", { "قطر": q(110, "میلی‌متر", 1) }, "شاخه", "متر").rate, 6);
  near(conv("تیر آهن", { "ارتفاع": q(16, "سانتی‌متر", 1) }, "متر", "شاخه").rate, 1 / 12);
  /* «عدد»ِ لوله (لولهٔ اگزوز، قطعه) شاخه نیست: بی طول، تبدیلی نیست */
  assert.equal(conv("لوله", { "قطر": q(110, "میلی‌متر", 1) }, "عدد", "متر").rate, null);
  assert.equal(conv("شیلنگ لاستیکی", { "طول": q(50, "سانتی‌متر") }, "عدد", "متر").rate, 0.5);
});

test("پویا — بسته، دست و ظرف: شمار و محتوای همان قلم", () => {
  assert.equal(conv("آچار", { "بسته بندی": "26 پارچه" }, "دست", "عدد").rate, 26);
  assert.equal(conv("پیچ گوشتی", { "بسته بندی": "7 عددی" }, "عدد", "دست").rate, 1 / 7);
  assert.equal(conv("پیچ", { "بسته بندی": "بسته‌ای" }, "بسته", "عدد").rate, null, "«بسته‌ای» شمار ندارد");
  assert.equal(conv("روغن", { "حجم": q(1, "لیتر") }, "عدد", "لیتر").rate, 1);
  near(conv("سیمان", { "وزن": q(50, "کیلوگرم") }, "پاکت", "تن").rate, 0.05);
  assert.equal(conv("سیمان", {}, "پاکت", "تن").rate, null);
  assert.equal(conv("توری", { "طول": q(6, "متر"), "عرض": q(2, "متر") }, "رول", "متر مربع").rate, 12);
  /* بسته به سنجش فقط با لایهٔ محتوای خودش، نه هندسهٔ یک عددِ درونش: طولِ ۲۰ سانتیِ یک بستِ کمربندی طولِ بسته نیست */
  assert.equal(conv("بست", { "طول": q(20, "سانتی‌متر") }, "بسته", "متر").rate, null);
});

