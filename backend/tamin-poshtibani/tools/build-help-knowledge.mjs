const strip = (s) => String(s == null ? "" : s).replace(/<br\s*\/?>/gi, "\n").replace(/<[^>]+>/g, "")
  .replace(/&nbsp;/g, " ").replace(/&laquo;/g, "«").replace(/&raquo;/g, "»").replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"')
  .replace(/[ \t]+/g, " ").replace(/\s*\n\s*/g, "\n").trim();

export function buildKnowledge() {
  const sb = { window: {} };
  vm.createContext(sb);
  vm.runInContext(readFileSync(join(ROOT, "frontend", "tamin-poshtibani", "help-content.js"), "utf8"), sb);
  const H = sb.window.TP_HELP || { area: {}, topics: {} };
  const byArea = new Map();
  for (const [k, t] of Object.entries(H.topics || {})) {
    const a = k.split(".")[0];
    if (!byArea.has(a)) byArea.set(a, []);
    const parts = [`### ${strip(t.title)} (${k})`];
    /* واژه‌نامه (gl.*): نامِ انگلیسی، توضیحِ یک‌صفحه‌ای و «بیشتر بخوانید» هم — دستیار می‌تواند اصطلاح را با منبعش توضیح دهد */
    if (t.en) parts.push(`انگلیسی: ${strip(t.en)}`);
    if (t.summary) parts.push(strip(t.summary));
    for (const s of t.sections || []) parts.push(`${strip(s.h)}:${s.p ? `\n${strip(s.p)}` : ""}${(s.li || []).length ? `\n${s.li.map((x) => `- ${strip(x)}`).join("\n")}` : ""}`);
    if ((t.steps || []).length) parts.push("گام‌ها:\n" + t.steps.map((s, i) => `${i + 1}. ${strip(s)}`).join("\n"));
    if ((t.tips || []).length) parts.push("نکته‌ها:\n" + t.tips.map((s) => `- ${strip(s)}`).join("\n"));
    if ((t.faq || []).length) parts.push("پرسش‌های رایج:\n" + t.faq.map((f) => `- پرسش: ${strip(f.q)}\n  پاسخ: ${strip(f.a)}`).join("\n"));
    if ((t.links || []).length) parts.push("بیشتر بخوانید:\n" + t.links.map((l) => `- ${strip(l.t)} — ${l.u}${l.paid ? (l.paid === "abs" ? " (پولی؛ چکیده آزاد)" : " (پولی)") : ""}`).join("\n"));
    byArea.get(a).push(parts.join("\n"));
  }
  const sections = [...byArea].map(([a, list]) => `## ${(H.area || {})[a] || a}\n\n${list.join("\n\n")}`);
  return `${OVERVIEW}\n# راهنمای صفحه‌به‌صفحه (همان متنِ دکمهٔ «راهنما»ی پنل‌ها)\n\n${sections.join("\n\n")}\n`;
}

const fnv = (s) => { let h = 0x811c9dc5; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193); } return (h >>> 0).toString(36); };
export function moduleText(k = buildKnowledge()) {
  return `/* ساخته‌شده با backend/tamin-poshtibani/tools/build-help-knowledge.mjs از help-content.js — دستی ویرایش نکنید */\n`
    + `export const HELP_KNOWLEDGE = ${JSON.stringify(k)};\nexport const HELP_KNOWLEDGE_FP = ${JSON.stringify(fnv(k))};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const k = buildKnowledge();
  writeFileSync(OUT, moduleText(k));
  console.log("help-knowledge.js:", k.length, "chars");
}
